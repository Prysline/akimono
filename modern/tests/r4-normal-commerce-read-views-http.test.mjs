/** Necessary read-only HTTP/v2 integration, not formal C player acceptance. */
import test from 'node:test';
import assert from 'node:assert/strict';
import {genuinePlayer} from './support/p3-genuine-v2-player.mjs';
test('R4 original warehouse and balance read models survive real local actions and both v2 generations',async t=>{
 const p=await genuinePlayer(t,{now:'896401',crossPeriod:true,fullCommerce:true});
 const row=id=>p.state.warehouse.rows.find(x=>x.itemId===id);
 const opening=p.state.news.rows.filter(row=>row.message==='高階鍛造實測開設新商店了。');
 assert.equal(opening.length,1);assert.equal(opening[0].mode,1);assert.equal(opening[0].id,0);assert.equal(opening[0].private,false);
 assert.equal(opening[0].wire,[p.state.world.nowSeconds,1,0,'高階鍛造實測開設新商店了。'].join('\t'));
 assert.ok(p.state.news.recentRows.some(row=>row.wire===opening[0].wire));
 assert.equal(p.state.world.period.disk.live['log0.cgi'].bytes,opening[0].wire+'\n');
 assert.equal(p.state.balance.source,'r4-frozen-inc-info-independent.v1');
 assert.equal(p.state.balance.shelfMaintenance,0);
 assert.equal(p.state.balance.foundedLabel,'00秒');
 assert.equal(p.state.settlementMenu.nextSettlementAtSeconds,p.state.nextSettlementAtSeconds);
 assert.equal(p.state.settlementMenu.secondsUntilSettlement,p.state.secondsUntilSettlement);
 assert.equal(p.state.settlementMenu.timezoneSeconds,32400);
 assert.equal(p.state.ownerClock.remainingSeconds,p.state.world.nowSeconds-p.state.shop.time);
 assert.equal(p.state.ownerClock.source,'r4-frozen-owner-clock.v1');
 assert.equal(p.state.ownerHelp.kind,'new-shop');
 assert.equal(p.state.ownerHelp.libraryChapter,1);
 assert.equal(p.state.ownerHelp.mailSupported,false);
 assert.equal(row(79).count,5);assert.equal(row(79).marketPrice,null);assert.deepEqual(p.state.warehouse.survey,[]);
 const logsBeforeGift=structuredClone(p.state.news.rows);
 await p.use(79,0);assert.equal(p.stock(9),1);assert.equal(row(9).count,1);assert.equal(row(9).storage,true);
 assert.deepEqual(p.state.news.rows,logsBeforeGift,'callback-free gift exchange produces no generic original USE log');
 assert.equal(p.state.world.period.disk.live['log0.cgi'].bytes,opening[0].wire+'\n');
 await p.list(79);
 assert.equal(p.state.ownerHelp.hasDisplayedStock,true);
 assert.deepEqual(p.state.showcaseView.rows,[{shelf:0,itemId:79,taxRate:0,tax:0}]);
 assert.equal(p.state.news.rows[0].message,'將禮物卷\\10,000陳列在展示架1上了。');
 assert.equal(p.state.news.rows[0].private,true);
 assert.equal(row(79).displayedStock,p.stock(79));assert.equal(row(79).marketPrice,10000);
 assert.deepEqual(p.state.warehouse.survey.map(x=>x.itemId),[79]);
 assert.equal(p.state.warehouse.survey[0].lowestPrice,10000);assert.equal(p.state.warehouse.survey[0].highestPrice,10000);
 const before=structuredClone({warehouse:p.state.warehouse,balance:p.state.balance,news:p.state.news,showcaseView:p.state.showcaseView});
 assert.equal(before.news.source,'r4-frozen-news-owner.v1');
 assert.ok(before.news.rows.some(row=>row.id===0));
 const first=await p.saveAndRestart(0);
 assert.deepEqual({warehouse:p.state.warehouse,balance:p.state.balance,news:p.state.news,showcaseView:p.state.showcaseView},before);
 assert.equal(p.state.news.rows.filter(row=>row.wire===opening[0].wire).length,1);
 const denied=await p.post('/api/discard',{itemId:9,count:1,expectedRevision:first.revision-1});
 assert.equal(denied.ok,false);assert.deepEqual(p.state.world,first);
 assert.deepEqual({warehouse:p.state.warehouse,balance:p.state.balance,news:p.state.news,showcaseView:p.state.showcaseView},before);
 await p.discard(9);
 assert.equal(p.stock(9),0);assert.equal(row(9),undefined,'no stock, sales or EXP: original row no longer qualifies');
 assert.equal(row(79).marketPrice,10000);
 const after=structuredClone({warehouse:p.state.warehouse,balance:p.state.balance,news:p.state.news,showcaseView:p.state.showcaseView});
 assert.equal(after.news.rows[0].id,1);assert.equal(after.news.rows[0].private,true);
 assert.match(after.news.rows[0].message,/被丟棄了$/);
 const second=await p.saveAndRestart(1);
 assert.equal(second.revision,first.revision+1);
 assert.deepEqual({warehouse:p.state.warehouse,balance:p.state.balance,news:p.state.news,showcaseView:p.state.showcaseView},after);
 await p.enoughTime(600);
 const beforeRemove=p.state.world;
 const removed=await p.post('/api/showcase',{expectedRevision:beforeRemove.revision,shelf:0,itemId:0,per:100});
 assert.equal(removed.code,'COMMITTED');
 assert.equal(p.stock(79),beforeRemove.shops[0].item[78]);
 assert.deepEqual(p.state.showcaseView.rows,[{shelf:0,itemId:0,taxRate:null,tax:null}]);
 assert.equal(p.state.ownerHelp.hasDisplayedStock,false);
 assert.equal(p.state.news.rows[0].message,'從展示架1下架了。');
 assert.equal(p.state.news.rows[0].private,true);
});

test('R4 wholesale detail uses actual market quote and follows purchase/reload without extra authority',async t=>{
 let purchased=false;
 const p=await genuinePlayer(t,{now:'896401',crossPeriod:true,fullCommerce:true,onPurchase(r,before,offer){
  if(offer.itemId!==78)return;
  assert.deepEqual(offer.detail,{source:'r4-frozen-buy-detail.v1',shopName:'市場',name:'轉職指南',nameLabel:'商品',info:'對於那些想換工作的人',scale:'組',price:offer.price,marketStock:offer.marketStock,owned:offer.owned,saleWarning:null,actionLabel:'購買'});
  assert.equal(r.details.unitPrice,offer.detail.price);
  assert.equal(r.state.world.shops[0].item[77],offer.detail.owned+1);
  purchased=true;
 }});
 await p.market(78);assert.equal(purchased,true);
 const current=p.state.marketOffers.find(x=>x.itemId===78);
 if(current){assert.equal(current.detail.owned,p.stock(78));assert.equal(current.detail.marketStock,current.marketStock);assert.equal(current.detail.price,current.price);}
 const before=structuredClone(p.state.marketOffers);
 await p.saveAndRestart(0);assert.deepEqual(p.state.marketOffers,before);
});
