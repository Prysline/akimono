import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createStandardStreetModule} from '../src/standard-street-module.mjs';
import {createPeriodMemoryWorld,createSourceReviewedMemoryWorldAdapter,executeMemoryCommand,encodeMemorySnapshot} from '../src/game-core-contract.mjs';
import {reviewOriginalPeriodBootstrap,createOriginalPeriodSeed} from '../src/original-period-world-seed.mjs';
import {beginReviewedWorldHistory,appendReviewedWorldHistory,verifyReviewedWorldHistory} from '../src/reviewed-world-time-history.mjs';
import {createReviewedHistoryCheckpointStore} from '../src/reviewed-history-checkpoint-store.mjs';
import {isReviewedOrdinaryCommand} from '../src/reviewed-ordinary-command-policy.mjs';
import {createLocalWorldSaveStore} from '../src/local-world-save-store.mjs';
import {createIndependentPeriodDiskStore} from '../src/r4-independent-period-disk-store.mjs';
import {createOwnerCredentialRecord,createCommittedOwnerCredentialReader,createCredentialOwnerAuthenticator,verifyOwnerCredential} from '../src/r4-owner-credential-record.mjs';
import {createStableOwnerSessions} from '../src/r4-stable-owner-sessions.mjs';
import {createAccountWorldPublisher} from '../src/r4-account-world-publisher.mjs';
import {loadNormalCommerceAuditSources} from './support/r4-source-inputs.mjs';
import {normalizeLocalSourceText} from '../src/local-source-text.mjs';

test('D61 repass real source CAS, private KDF, source history and disk, old-session revocation and asynchronous revision/session races',async t=>{
 const directory=await mkdtemp(join(tmpdir(),'akimono-account-repass-'));t.after(()=>rm(directory,{recursive:true,force:true}));
 const sources=Object.fromEntries(Object.entries(await loadNormalCommerceAuditSources()).map(([k,v])=>[k,normalizeLocalSourceText(v)]));
 const read=async p=>normalizeLocalSourceText(await readFile(new URL(p,import.meta.url),'utf8'));
 const membershipSource=await read('./original-perl/pinned-membership-user.cgi'),loginSource=await read('./original-perl/pinned-login.cgi');
 const opts={...sources,enableReviewedNormalTime:true,enableReviewedCrossPeriod:true};
 assert.throws(()=>createStandardStreetModule({...opts,enableReviewedAccountPasswordChange:true,originalMembershipSource:membershipSource+'\n'}),/repass/);
 const streetModule=createStandardStreetModule({...opts,enableReviewedAccountPasswordChange:true,originalMembershipSource:membershipSource});
 const reviewed=reviewOriginalPeriodBootstrap({periodSource:sources.originalPeriodSource,adminSource:sources.originalAdminInitSource,readSource:sources.originalDataReadSource,writeSource:sources.originalDataWriteSource,reviewedB41:streetModule.reviewedB41});
 const createInitialWorld=({worldId,nowSeconds})=>createPeriodMemoryWorld({worldId,streetId:streetModule.id,nowSeconds,period:createOriginalPeriodSeed(reviewed)});
 const historyPolicy={streetModule,createInitialWorld,isOrdinaryCommand:c=>isReviewedOrdinaryCommand(c,streetModule),verifyOrdinaryDraws:(_world,c)=>!Object.hasOwn(c,'randomDraws')};
 const checkpointStore=createReviewedHistoryCheckpointStore({directory,sourceFingerprint:'a'.repeat(64),interpreter:'controlled-repass-source',crossPeriod:true});
 const periodDiskStore=createIndependentPeriodDiskStore({directory});
 const openStore=()=>createLocalWorldSaveStore({directory,accountMode:true,historyReplay:{checkpointStore,periodDiskStore,verify:({world,proof,generation})=>verifyReviewedWorldHistory({world,proof,generation,checkpointStore,...historyPolicy})}});
 const repo=createSourceReviewedMemoryWorldAdapter({initialWorld:createInitialWorld({worldId:'repass-fixture',nowSeconds:1000000}),streetModule});
 const initial=executeMemoryCommand({repository:repo,streetModule,command:{kind:'initialize-source-market',expectedRevision:0}});
 assert.equal(initial.ok,true);
 // Controlled account bootstrap, NOT formal registration or login policy.
 const command={kind:'open-shop',expectedRevision:1,shopId:1,ownerName:'owner',shopName:'source shop'};
 const opened=executeMemoryCommand({repository:repo,streetModule,command});assert.equal(opened.ok,true);
 const proof=appendReviewedWorldHistory({proof:beginReviewedWorldHistory(initial.world),before:initial.world,command,result:opened,...historyPolicy});
 const binding={worldId:opened.world.worldId,streetId:streetModule.id,shopId:1,ownerName:'owner'};
 const record=await createOwnerCredentialRecord({newSource:sources.originalNewSource,binding,password:'old_pw'});
 const store=openStore();store.save(opened.world,{expectedGeneration:0,careerProof:proof,ownerCredentials:[record]});
 let publisher;
 const reader=createCommittedOwnerCredentialReader({readCommittedSnapshot:()=>publisher.readCommittedSnapshot()});
 const sessions=createStableOwnerSessions({configSource:sources.originalConfigSource,readSource:sources.originalDataReadSource,loginSource,
   readWorld:()=>publisher.read(),authenticateOwner:createCredentialOwnerAuthenticator({readCredentialRecord:reader,readCredentials:r=>r.credentials}),readSessionToken:r=>r.token,clock:()=>1000000});
 publisher=createAccountWorldPublisher({saveStore:store,streetModule,historyPolicy,checkpointStore,
   passwordChange:{membershipSource,readSource:sources.originalDataReadSource,itemDsl:sources.itemDsl,sessions}});
 const login=password=>sessions.issue({credentials:{ownerName:'owner',password}});
 let request=await login('old_pw');
 const body=(expectedRevision,password='0',confirmation=password)=>({expectedRevision,password,confirmation});
 assert.equal(publisher.commit({kind:'change-owner-password',expectedRevision:2,shopId:1}).code,'ACCOUNT_TRANSITION_NOT_REVIEWED');
 assert.equal((await publisher.changePassword({request:{token:'invalid'},body:body(2)})).code,'OWNER_SESSION_DENIED');
 assert.equal((await publisher.changePassword({request,body:{...body(2),shopId:1}})).code,'BAD_REQUEST');
 assert.equal((await publisher.changePassword({request,body:body(2,'0','different')})).code,'PASSWORD_CHANGE_REJECTED');
 assert.deepEqual(publisher.status(),{generation:1,revision:2});
 const raced=publisher.changePassword({request,body:body(2)});
 const edit={kind:'edit-showcase',expectedRevision:2,shopId:1,itemId:0,shelf:0,per:100,priceOverride:0};
 assert.equal(publisher.commit(edit).ok,true);
 assert.equal((await raced).code,'REVISION_CONFLICT');
 assert.deepEqual(publisher.readCommittedSnapshot().ownerCredentials,[record]);
 const logoutRace=publisher.changePassword({request,body:body(3)});
 assert.equal(sessions.revoke(request),true);
 assert.equal((await logoutRace).code,'OWNER_SESSION_DENIED');
 request=await login('old_pw');
 const before=publisher.read();
 const result=await publisher.changePassword({request,body:body(3)});
 assert.equal(result.ok,true);
 assert.deepEqual(publisher.status(),{generation:3,revision:4});
 assert.equal(result.world.shops[0].lastlogin,before.nowSeconds);
 assert.equal(result.world.shops[0].pass,'');
 assert.equal(result.world.shops[0].money,before.shops[0].money);
 assert.equal(result.world.shops[0].time,before.shops[0].time);
 assert.deepEqual(result.world.shops[0].item,before.shops[0].item);
 for(const name of ['log0.cgi','log1.cgi','log2.cgi'])
   assert.deepEqual(result.world.period.disk.live[name],before.period.disk.live[name]);
 assert.throws(()=>sessions.resolveAuthenticatedActor({request,world:result.world}),/session denied/);
 await assert.rejects(login('old_pw'),/login denied/);
 const newSession=await login('0');assert.equal(sessions.resolveAuthenticatedActor({request:newSession,world:result.world}).shopId,1);
 const recovered=openStore().loadCommittedAccountState();
 assert.equal(recovered.generation,3);
 assert.equal(encodeMemorySnapshot(recovered.world),encodeMemorySnapshot(result.world));
 assert.deepEqual(recovered.careerProof.commands.at(-1),{kind:'change-owner-password',expectedRevision:3,shopId:1});
 const successor=recovered.ownerCredentials[0];assert.notEqual(successor.salt,record.salt);
 assert.equal(await verifyOwnerCredential({record:successor,binding,password:'0'}),true);
 assert.equal(await verifyOwnerCredential({record:successor,binding,password:'old_pw'}),false);
 const publicWire=JSON.stringify([result,recovered.careerProof,recovered.world]);
 assert.ok(!publicWire.includes(record.hash)&&!publicWire.includes(successor.hash)&&!publicWire.includes('old_pw'));
});
